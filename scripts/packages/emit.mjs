// Turns icon node trees into the files of the React and Vue packages (ICN-159).
// Output is plain JavaScript (ESM and CommonJS) plus type declarations: no JSX, no bundler, nothing to transpile.
// Deterministic: the same icons always produce byte-identical files (sorted, LF line endings, no dates).
import fs from 'node:fs';
import path from 'node:path';
import { componentName } from './naming.mjs';

export const FRAMEWORKS = ['react', 'vue'];

/** React wants camelCase attribute names (stroke-width becomes strokeWidth); Vue takes SVG attributes as written. */
export function attrName(framework, name) {
  if (framework !== 'react') return name;
  if (name.startsWith('data-') || name.startsWith('aria-')) return name;
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

/** One node as a JavaScript literal: ['path', { d: '...' }] or ['g', { ... }, [children]]. */
function nodeLiteral(framework, node, indent) {
  const attrs = node.attrs.map(([n, v]) => `${key(attrName(framework, n))}: ${JSON.stringify(v)}`);
  const head = `['${node.tag}', { ${attrs.join(', ')} }`;
  if (!node.children.length) return `${indent}${head}]`;
  const inner = node.children.map((c) => nodeLiteral(framework, c, `${indent}  `)).join(',\n');
  return `${indent}${head}, [\n${inner},\n${indent}]]`;
}

const nodesLiteral = (framework, nodes) => nodes.map((n) => nodeLiteral(framework, n, '  ')).join(',\n');

const banner = (slug) => `// Generated from icons/${slug}.svg by scripts/packages. Do not edit.\n`;

/** The module of one icon, as ES module or CommonJS. */
export function iconModule(framework, format, slug, nodes) {
  const name = componentName(slug);
  const body = `createIcon('${name}', [\n${nodesLiteral(framework, nodes)},\n])`;
  if (format === 'esm') {
    return [
      banner(slug) + "import { createIcon } from '../create-icon.js';",
      '',
      `export const ${name} = ${body};`,
      `export { ${name} as ${name}Icon };`,
      `export default ${name};`,
      '',
    ].join('\n');
  }
  return [
    banner(slug) + "'use strict';",
    "const { createIcon } = require('../create-icon.cjs');",
    '',
    `const ${name} = ${body};`,
    `module.exports = ${name};`,
    `module.exports.${name} = ${name};`,
    `module.exports.${name}Icon = ${name};`,
    'module.exports.default = module.exports;',
    '',
  ].join('\n');
}

/** The type declaration of one icon. */
export function iconTypes(slug) {
  const name = componentName(slug);
  return [
    banner(slug) + "import type { Icon } from '../types.js';",
    '',
    `export declare const ${name}: Icon;`,
    `export { ${name} as ${name}Icon };`,
    `export default ${name};`,
    '',
  ].join('\n');
}

/** The index of the package: every icon, by name. */
export function indexModule(format, slugs) {
  const names = slugs.map((s) => [s, componentName(s)]);
  if (format === 'esm') {
    return [
      '// Generated by scripts/packages. Do not edit.',
      ...names.map(([s, n]) => `export { ${n}, ${n}Icon } from './icons/${s}.js';`),
      '',
    ].join('\n');
  }
  return [
    "// Generated by scripts/packages. Do not edit.\n'use strict';",
    ...names.flatMap(([s, n]) => [
      `exports.${n} = require('./icons/${s}.cjs').${n};`,
      `exports.${n}Icon = exports.${n};`,
    ]),
    '',
  ].join('\n');
}

export function indexTypes(slugs) {
  return [
    '// Generated by scripts/packages. Do not edit.',
    "export type { Icon, IconProps } from './types.js';",
    ...slugs.map((s) => `export { ${componentName(s)}, ${componentName(s)}Icon } from './icons/${s}.js';`),
    '',
  ].join('\n');
}

const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};

/**
 * Writes one package's dist folder. `icons` is [{ name, nodes }]; `srcDir` holds the hand-written runtime
 * (create-icon.js, create-icon.cjs, types.d.ts) which is copied next to the generated files.
 */
export function writePackage(framework, icons, srcDir, outDir) {
  fs.rmSync(outDir, { recursive: true, force: true });
  const sorted = [...icons].sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const { name, nodes } of sorted) {
    write(path.join(outDir, 'icons', `${name}.js`), iconModule(framework, 'esm', name, nodes));
    write(path.join(outDir, 'icons', `${name}.cjs`), iconModule(framework, 'cjs', name, nodes));
    write(path.join(outDir, 'icons', `${name}.d.ts`), iconTypes(name));
  }
  const slugs = sorted.map((i) => i.name);
  write(path.join(outDir, 'index.js'), indexModule('esm', slugs));
  write(path.join(outDir, 'index.cjs'), indexModule('cjs', slugs));
  write(path.join(outDir, 'index.d.ts'), indexTypes(slugs));
  for (const file of ['create-icon.js', 'create-icon.cjs', 'types.d.ts']) {
    fs.copyFileSync(path.join(srcDir, file), path.join(outDir, file));
  }
  return sorted.length;
}
